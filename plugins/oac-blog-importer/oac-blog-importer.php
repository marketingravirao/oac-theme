function oac_import_blog_posts() {
	if ( ! current_user_can( 'manage_options' ) ) {
		wp_die( esc_html__( 'You do not have permission to import posts.', 'oac-theme' ) );
	}

	check_admin_referer( 'oac_import_insights_posts' );

	$created = 0;
	$skipped = 0;
	$category = term_exists( 'Astrology Insights', 'category' );
	if ( ! $category ) {
		$category = wp_insert_term( 'Astrology Insights', 'category' );
	}
	$category_id = is_array( $category ) ? (int) $category['term_id'] : (int) $category;

	foreach ( oac_importable_blog_posts() as $post_data ) {
		$existing = get_posts(
			array(
				'post_type' => 'post',
				'post_status' => array( 'publish', 'draft', 'pending', 'private' ),
				'meta_key' => '_oac_insights_source',
				'meta_value' => $post_data['slug'],
				'posts_per_page' => 1,
				'fields' => 'ids',
			)
		);

		if ( $existing ) {
			$skipped++;
			continue;
		}

		$gmt_date = get_gmt_from_date( $post_data['date'] );
		$post_id = wp_insert_post(
			array(
				'post_title' => $post_data['title'],
				'post_name' => $post_data['slug'],
				'post_excerpt' => $post_data['excerpt'],
				'post_content' => $post_data['content'],
				'post_status' => 'publish',
				'post_type' => 'post',
				'post_date' => $post_data['date'],
				'post_date_gmt' => $gmt_date,
				'post_category' => array( $category_id ),
			),
			true
		);

		if ( is_wp_error( $post_id ) ) {
			continue;
		}

		update_post_meta( $post_id, '_oac_insights_source', $post_data['slug'] );
		update_post_meta( $post_id, '_oac_insights_source_url', 'https://blogs.onlineastrologyclasses.com/post/' . $post_data['slug'] );

		if ( ! empty( $post_data['keywords'] ) ) {
			wp_set_object_terms( $post_id, $post_data['keywords'], 'post_tag', false );
		}

		if ( ! empty( $post_data['image'] ) && ! has_post_thumbnail( $post_id ) ) {
			require_once ABSPATH . 'wp-admin/includes/file.php';
			require_once ABSPATH . 'wp-admin/includes/media.php';
			require_once ABSPATH . 'wp-admin/includes/image.php';
			$attachment_id = media_sideload_image( $post_data['image'], $post_id, $post_data['title'], 'id' );
			if ( ! is_wp_error( $attachment_id ) ) {
				set_post_thumbnail( $post_id, (int) $attachment_id );
			}
		}

		$created++;
	}

	wp_safe_redirect( add_query_arg( array( 'page' => 'oac-blog-importer', 'imported' => $created, 'skipped' => $skipped ), admin_url( 'tools.php' ) ) );
	exit;
}
add_action( 'admin_post_oac_import_insights_posts', 'oac_import_blog_posts' );

function oac_blog_importer_admin_page() {
	if ( isset( $_GET['imported'] ) ) {
		echo '<div class="notice notice-success"><p>' . sprintf( esc_html__( '%1$d posts imported and %2$d duplicates skipped.', 'oac-theme' ), absint( $_GET['imported'] ), absint( $_GET['skipped'] ?? 0 ) ) . '</p></div>';
	}

	echo '<div class="wrap"><h1>' . esc_html__( 'Import Insights Blog Posts', 'oac-theme' ) . '</h1>';
	echo '<p>' . esc_html__( 'Imports the 6 scraped Online Astrology Classes Insights articles as WordPress posts. Existing source posts are skipped.', 'oac-theme' ) . '</p>';
	echo '<form method="post" action="' . esc_url( admin_url( 'admin-post.php' ) ) . '">';
	wp_nonce_field( 'oac_import_insights_posts' );
	echo '<input type="hidden" name="action" value="oac_import_insights_posts">';
	submit_button( __( 'Import 6 Blog Posts', 'oac-theme' ) );
	echo '</form></div>';
}

